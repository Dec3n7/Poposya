from abc import ABC, abstractmethod


class ISettingsProvider(ABC):
    """Порт пер-гильдийных настроек. get возвращает значение сервера или
    переданный дефолт (обычно — глобальное значение из .env). Синхронный:
    реализация держит переопределения в памяти, горячий путь без запросов к БД."""

    @abstractmethod
    def get(self, guild_id: int, key: str, default): ...

    def upgrade_hint(self, guild_id: int | None) -> str:
        """Короткий нудж на подписку для сообщений о лимите (голос Попоси). Базово
        пусто; тарифный кламп-провайдер переопределяет и возвращает подсказку, когда
        сервер на free упирается в тарифный потолок. Живёт на провайдере, т.к. только
        он знает тариф гильдии — коги уже держат его как единый шлюз настроек."""
        return ""
