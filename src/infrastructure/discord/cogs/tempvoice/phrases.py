def not_owner(owner_id: int) -> str:
    """Отказ должен говорить, что делать дальше, а не просто «нельзя»."""
    return (
        f"Каморка не твоя — хозяин тут <@{owner_id}>. Если он ушёл, а ты внутри — жми 👑 Забрать."
    )


